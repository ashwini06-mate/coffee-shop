export function money(value) {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(value)
}

export function buildLine(item, options = {}) {
  const sizes = item.sizes || []
  const size = options.size || sizes.find((entry) => entry.default) || sizes[0] || null
  const milkOptions = item.milkOptions || []
  const milk = milkOptions.length
    ? options.milk || item.defaultMilk || milkOptions[0]
    : null
  const price = size ? size.price : item.price
  const detail = []

  if (size && sizes.length > 1) detail.push(size.label)
  if (milk && milkOptions.length > 1) detail.push(milk)
  if (item.weight) detail.push(item.weight)

  const lineId = [
    item.id,
    size && sizes.length > 1 ? size.id : null,
    milk && milkOptions.length > 1 ? milk : null,
  ]
    .filter(Boolean)
    .join('__')

  return {
    lineId,
    productId: item.id,
    name: item.name,
    detail: detail.join(' · '),
    price,
    qty: 1,
  }
}
